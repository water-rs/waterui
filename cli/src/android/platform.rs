fn gradle_cmd(
    host: &Host,
    gradlew: &Path,
    backend_path: &Path,
    tasks: &[&str],
) -> smol::process::Command {
    let mut cmd = host.command(gradlew);
    cmd.args(tasks).arg("--project-dir").arg(backend_path);
    cmd
}

/// Run the Gradle wrapper inside `backend_path` on `tasks`, wiring the JDK
/// and SDK the toolchain resolves plus any corporate proxy properties.
///
/// A failing build reports the process status and both captured streams.
/// When those streams carry no Gradle failure — the wrapper banner alone,
/// which is what a client that exits before forwarding the build result
/// prints — the report adds the failure excerpt from the daemon log written
/// during this invocation, or the head of a JVM crash log written beside
/// the project. The shared tail of every Gradle invocation the CLI drives.
pub(crate) async fn run_gradle_tasks(
    host: &Host,
    backend_path: &Path,
    tasks: &[&str],
    extra_envs: &[(&str, String)],
) -> eyre::Result<()> {
    // The scaffold ships the wrapper scripts and properties but not the jar
    // — the repository carries no binary files, so the jar is materialized
    // here, the first point a Gradle task can run. A project generated by an
    // older CLI (jar embedded then) or one whose jar a cleanup removed is
    // healed the same way.
    crate::project_model::gradle_wrapper::ensure(host, backend_path)
        .await
        .wrap_err_with(|| format!("preparing the Gradle wrapper in {}", backend_path.display()))?;

    let gradlew = backend_path.join(if cfg!(windows) {
        "gradlew.bat"
    } else {
        "gradlew"
    });

    // Set JAVA_HOME to Android Studio's bundled JDK to avoid JDK version conflicts
    // (e.g., Homebrew's JDK 25 is not supported by Android Gradle Plugin)
    let mut cmd = gradle_cmd(host, &gradlew, backend_path, tasks);
    if let Some(java_home) = Java::detect_home(host).await {
        cmd.env("JAVA_HOME", java_home);
    }
    if let Some(sdk_path) = AndroidSdk::detect_path(host) {
        cmd.env("ANDROID_HOME", &sdk_path)
            .env("ANDROID_SDK_ROOT", &sdk_path);
    }
    // WATERUI_ANDROID_UNSIGNED is the package step's signal to skip the
    // generated release signingConfig; a value inherited from the caller's
    // own environment would silently unsigned an asked-for signed package, so
    // only the value extra_envs supplies may reach Gradle.
    cmd.env_remove(crate::android::signing::UNSIGNED_ENV);
    for (key, value) in extra_envs {
        cmd.env(key, value);
    }
    apply_gradle_proxy_env(host, &mut cmd)?;

    // Captured before the process starts so a daemon log from an earlier
    // build — still the newest file when this client writes none — is not
    // reported as this failure.
    let started = SystemTime::now();
    let output = cmd.output().await?;

    if !output.status.success() {
        bail!(
            "{}",
            gradle_failure_report(host, backend_path, started, &output).await
        );
    }
    Ok(())
}

/// Bytes read from the end of a daemon or crash log. The failure is written
/// last; earlier debug logging is not part of the report.
const GRADLE_LOG_TAIL_BYTES: u64 = 256 * 1024;

/// Non-metadata lines kept from a `FAILURE:` block.
const GRADLE_FAILURE_EXCERPT_LINES: usize = 80;

/// `[ERROR]` / `Exception in thread` lines kept when a daemon log has no
/// `FAILURE:` block.
const GRADLE_ERROR_EXCERPT_LINES: usize = 40;

/// Lines kept from the head of a JVM crash log.
const JVM_CRASH_EXCERPT_LINES: usize = 30;

const GRADLE_FAILURE_HEADER: &str = "FAILURE: Build failed with an exception.";

/// Markers a Gradle console uses for the build result. The wrapper banner
/// and the configuration-cache notice contain none of them.
const GRADLE_FAILURE_MARKERS: &[&str] = &["FAILURE:", "* What went wrong:", "BUILD FAILED"];

const DAEMON_METADATA_MARKERS: &[&str] = &[
    " [DEBUG] ",
    " [INFO] ",
    " [ERROR] ",
    " [WARN] ",
    " [LIFECYCLE] ",
    " [TRACE] ",
];

fn append_block(message: &mut String, text: &str) {
    let text = text.trim();
    if text.is_empty() {
        return;
    }
    message.push('\n');
    message.push_str(text);
}

fn exit_status_summary(status: ExitStatus) -> String {
    #[cfg(unix)]
    {
        use std::os::unix::process::ExitStatusExt as _;
        if let Some(signal) = status.signal() {
            return format!("killed by signal {signal}");
        }
    }
    status.code().map_or_else(
        || format!("status {status}"),
        |code| format!("exit code {code}"),
    )
}

/// `GRADLE_USER_HOME` when the host sets it, otherwise `$HOME/.gradle` —
/// the directory the Gradle client and this report both read.
fn gradle_user_home(host: &Host) -> Option<PathBuf> {
    if let Some(configured) = host.env_string("GRADLE_USER_HOME") {
        let configured = configured.trim();
        if !configured.is_empty() {
            return Some(PathBuf::from(configured));
        }
    }
    host.home_dir().map(|home| home.join(".gradle"))
}

fn gradle_output_has_failure(stdout: &str, stderr: &str) -> bool {
    GRADLE_FAILURE_MARKERS
        .iter()
        .any(|marker| stdout.contains(marker) || stderr.contains(marker))
}

/// A timestamped daemon-log line (`2024-... [DEBUG] ...`), as opposed to the
/// plain `FAILURE:` block Gradle copies into the same file.
fn is_daemon_metadata_line(line: &str) -> bool {
    line.as_bytes().first().is_some_and(u8::is_ascii_digit)
        && DAEMON_METADATA_MARKERS
            .iter()
            .any(|marker| line.contains(marker))
}

fn daemon_failure_excerpt(log: &str) -> Option<String> {
    let lines: Vec<&str> = log.lines().collect();
    if let Some(start) = lines
        .iter()
        .rposition(|line| !is_daemon_metadata_line(line) && line.contains(GRADLE_FAILURE_HEADER))
    {
        return nonempty(&capped_join(
            lines[start..]
                .iter()
                .copied()
                .filter(|line| !is_daemon_metadata_line(line)),
            GRADLE_FAILURE_EXCERPT_LINES,
        ));
    }
    let errors = lines
        .iter()
        .copied()
        .filter(|line| line.contains(" [ERROR] ") || line.contains("Exception in thread"));
    nonempty(&tail_join(errors, GRADLE_ERROR_EXCERPT_LINES))
}

fn capped_join<'a>(lines: impl Iterator<Item = &'a str>, cap: usize) -> String {
    lines.take(cap).collect::<Vec<_>>().join("\n")
}

fn tail_join<'a>(lines: impl Iterator<Item = &'a str>, cap: usize) -> String {
    let lines: Vec<&str> = lines.collect();
    let start = lines.len().saturating_sub(cap);
    lines[start..].join("\n")
}

fn nonempty(text: &str) -> Option<String> {
    let text = text.trim();
    (!text.is_empty()).then(|| text.to_owned())
}

fn read_log_tail(path: &Path) -> Option<String> {
    let metadata = std::fs::metadata(path).ok()?;
    if !metadata.file_type().is_file() {
        return None;
    }
    let mut file = std::fs::File::open(path).ok()?;
    let length = metadata.len();
    let truncated = length > GRADLE_LOG_TAIL_BYTES;
    if truncated {
        file.seek(std::io::SeekFrom::Start(length - GRADLE_LOG_TAIL_BYTES))
            .ok()?;
    }
    let mut bytes = Vec::new();
    file.read_to_end(&mut bytes).ok()?;
    if truncated && let Some(split) = bytes.iter().position(|byte| *byte == b'\n') {
        bytes = bytes.split_off(split + 1);
    }
    Some(String::from_utf8_lossy(&bytes).into_owned())
}

fn is_daemon_log_name(name: &str) -> bool {
    name.starts_with("daemon-") && name.ends_with(".out.log")
}

fn is_crash_log_name(name: &str) -> bool {
    name.starts_with("hs_err_pid")
        && Path::new(name)
            .extension()
            .is_some_and(|ext| ext.eq_ignore_ascii_case("log"))
}

fn newest_matching_file(
    dir: &Path,
    started: SystemTime,
    matches: fn(&str) -> bool,
) -> Option<(SystemTime, PathBuf)> {
    let mut best: Option<(SystemTime, PathBuf)> = None;
    for entry in std::fs::read_dir(dir).ok()?.flatten() {
        let name = entry.file_name();
        let Some(name) = name.to_str() else {
            continue;
        };
        if !matches(name) {
            continue;
        }
        let Ok(metadata) = entry.metadata() else {
            continue;
        };
        if !metadata.is_file() {
            continue;
        }
        let Ok(modified) = metadata.modified() else {
            continue;
        };
        if modified < started {
            continue;
        }
        if best.as_ref().is_none_or(|(when, _)| modified > *when) {
            best = Some((modified, entry.path()));
        }
    }
    best
}

fn newest_daemon_log(gradle_home: &Path, started: SystemTime) -> Option<PathBuf> {
    let mut best: Option<(SystemTime, PathBuf)> = None;
    let versions = std::fs::read_dir(gradle_home.join("daemon")).ok()?;
    for version in versions.flatten() {
        let Ok(file_type) = version.file_type() else {
            continue;
        };
        if !file_type.is_dir() {
            continue;
        }
        consider(
            &mut best,
            newest_matching_file(&version.path(), started, is_daemon_log_name),
        );
    }
    best.map(|(_, path)| path)
}

fn crash_log_dirs(host: &Host, backend_path: &Path, gradle_home: Option<&Path>) -> Vec<PathBuf> {
    let mut dirs = vec![host.cwd().to_path_buf(), backend_path.to_path_buf()];
    if let Some(home) = gradle_home {
        dirs.push(home.to_path_buf());
    }
    dirs.sort();
    dirs.dedup();
    dirs
}

fn newest_crash_log(dirs: &[PathBuf], started: SystemTime) -> Option<PathBuf> {
    let mut best: Option<(SystemTime, PathBuf)> = None;
    for dir in dirs {
        consider(
            &mut best,
            newest_matching_file(dir, started, is_crash_log_name),
        );
    }
    best.map(|(_, path)| path)
}

fn consider(best: &mut Option<(SystemTime, PathBuf)>, candidate: Option<(SystemTime, PathBuf)>) {
    let Some((modified, path)) = candidate else {
        return;
    };
    if best.as_ref().is_none_or(|(when, _)| modified > *when) {
        *best = Some((modified, path));
    }
}

/// The daemon log's failure block, or the head of a JVM crash log, when the
/// captured console does not already contain one. `None` when this
/// invocation wrote neither.
fn gradle_failure_attachment(
    gradle_home: Option<&Path>,
    crash_dirs: &[PathBuf],
    started: SystemTime,
) -> Option<String> {
    if let Some(home) = gradle_home
        && let Some(path) = newest_daemon_log(home, started)
        && let Some(text) = read_log_tail(&path)
        && let Some(excerpt) = daemon_failure_excerpt(&text)
    {
        return Some(format!(
            "Gradle daemon log ({}):\n{excerpt}",
            path.display()
        ));
    }
    let path = newest_crash_log(crash_dirs, started)?;
    let excerpt = crash_excerpt(&read_log_tail(&path)?)?;
    Some(format!("JVM crash log ({}):\n{excerpt}", path.display()))
}

fn crash_excerpt(text: &str) -> Option<String> {
    nonempty(&capped_join(text.lines(), JVM_CRASH_EXCERPT_LINES))
}

async fn gradle_failure_report(
    host: &Host,
    backend_path: &Path,
    started: SystemTime,
    output: &std::process::Output,
) -> String {
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);
    let mut message = format!(
        "Gradle build failed in {} ({}):",
        backend_path.display(),
        exit_status_summary(output.status),
    );
    append_block(&mut message, &stdout);
    append_block(&mut message, &stderr);
    // The pipes are the console Gradle actually wrote. They are complete:
    // a normal failure puts `FAILURE:` on stderr. This branch is the other
    // exit — banner and configuration-cache notice, no build result — whose
    // diagnostic is in the daemon log (or a JVM crash log) instead.
    if gradle_output_has_failure(&stdout, &stderr) {
        return message;
    }
    let gradle_home = gradle_user_home(host);
    let crash_dirs = crash_log_dirs(host, backend_path, gradle_home.as_deref());
    let attachment =
        unblock(move || gradle_failure_attachment(gradle_home.as_deref(), &crash_dirs, started))
            .await;
    if let Some(attachment) = attachment {
        message.push('\n');
        append_block(&mut message, &attachment);
    }
    message
}

fn apply_gradle_proxy_env(host: &Host, cmd: &mut smol::process::Command) -> eyre::Result<()> {
    let proxy_properties = java_proxy_properties_from_env(host)?;
    if proxy_properties.is_empty() {
        return Ok(());
    }

    cmd.args(&proxy_properties);

    let mut gradle_opts = proxy_properties.join(" ");
    if let Some(existing) = host.env_string("GRADLE_OPTS")
        && !existing.trim().is_empty()
    {
        gradle_opts.push(' ');
        gradle_opts.push_str(&existing);
    }
    cmd.env("GRADLE_OPTS", gradle_opts);
    Ok(())
}

/// Get the NDK host tag based on the current machine's OS and architecture.
///
/// On Apple Silicon, prefer the native `darwin-arm64` toolchain when present,
/// falling back to `darwin-x86_64` for older Android NDK releases (Rosetta).
fn ndk_host_tag(ndk_path: &Path) -> &'static str {
    use target_lexicon::{Architecture, OperatingSystem, Triple};

    let host = Triple::host();

    match (&host.operating_system, &host.architecture) {
        (OperatingSystem::Darwin(_), Architecture::Aarch64(_)) => {
            let native = ndk_path
                .join("toolchains/llvm/prebuilt")
                .join("darwin-arm64");
            if native.exists() {
                "darwin-arm64"
            } else {
                "darwin-x86_64"
            }
        }
        (OperatingSystem::Darwin(_), _) => "darwin-x86_64",
        (OperatingSystem::Windows, _) => "windows-x86_64",
        // NDK doesn't have native ARM64 Linux builds
        (OperatingSystem::Linux, _) => "linux-x86_64",
        _ => panic!("Unsupported host triple for Android NDK: {host}"),
    }
}

fn ndk_bin_dir(ndk_path: &Path) -> PathBuf {
    ndk_path
        .join("toolchains/llvm/prebuilt")
        .join(ndk_host_tag(ndk_path))
        .join("bin")
}

/// An LLVM binary tool (`llvm-strip`, `llvm-readelf`, …) from the NDK's
/// prebuilt host toolchain — the same `prebuilt/<host-tag>/bin` directory
/// the linker and `ar` resolve from, with the host's executable suffix
/// (`llvm-strip.exe` on Windows).
///
/// # Errors
/// Returns an error when the NDK's bin directory does not ship `tool` —
/// naming the tool and where it was looked for.
pub(crate) fn ndk_llvm_tool(ndk_path: &Path, tool: &str) -> eyre::Result<PathBuf> {
    let path = ndk_bin_dir(ndk_path).join(format!("{tool}{}", std::env::consts::EXE_SUFFIX));
    if path.is_file() {
        Ok(path)
    } else {
        eyre::bail!(
            "the NDK at {} ships no {tool} — expected {}",
            ndk_path.display(),
            path.display()
        )
    }
}

/// Get the NDK ar path.
fn ndk_ar_path(ndk_path: &Path) -> PathBuf {
    ndk_bin_dir(ndk_path).join("llvm-ar")
}

fn ndk_clang_path(ndk_path: &Path, abi: AndroidAbi, cxx: bool, api_level: u32) -> PathBuf {
    let suffix = if cxx { "clang++" } else { "clang" };
    ndk_bin_dir(ndk_path).join(format!("{}{api_level}-{suffix}", abi.ndk_target()))
}

/// Get the NDK clang linker path for the given ABI.
fn ndk_linker_path(ndk_path: &Path, abi: AndroidAbi, api_level: u32) -> PathBuf {
    ndk_clang_path(ndk_path, abi, false, api_level)
}

/// Create a wrapper `CMake` toolchain file that sets `ANDROID_ABI` before including
/// the NDK's toolchain. This is required because cmake-rs doesn't pass `ANDROID_ABI`
/// as a -D define, causing the NDK toolchain to default to armeabi-v7a.
///
/// Returns the path to the created wrapper toolchain file.
async fn create_android_toolchain_wrapper(
    host: &Host,
    ndk_path: &Path,
    abi: AndroidAbi,
    api_level: u32,
) -> eyre::Result<PathBuf> {
    // Create wrapper in a temp directory that persists for the build
    let wrapper_dir = host.temp_dir().join("waterui-cmake-toolchains");
    fs::create_dir_all(&wrapper_dir).await?;

    let wrapper_path = wrapper_dir.join(format!("android-{}.cmake", abi.as_str()));
    let ndk_toolchain = ndk_path.join("build/cmake/android.toolchain.cmake");

    let content = format!(
        include_str!("android_toolchain_wrapper.cmake.tpl"),
        abi = abi.as_str(),
        api_level = api_level,
        ndk_toolchain = ndk_toolchain.display(),
        asm_compiler = ndk_clang_path(ndk_path, abi, false, api_level).display(),
    );
    crate::templates::write_file_if_changed(&wrapper_path, content.as_bytes()).await?;

    Ok(wrapper_path)
}

/// Get the NDK clang++ (C++ compiler) path for the given ABI.
fn ndk_cxx_path(ndk_path: &Path, abi: AndroidAbi, api_level: u32) -> PathBuf {
    ndk_clang_path(ndk_path, abi, true, api_level)
}

/// Get the path to `libc++_shared.so` in the NDK.
///
/// NDK r23+ ships it under `sysroot/usr/lib/<triple>/`, while older Android
/// NDK releases used `sources/cxx-stl/llvm-libc++/libs/<abi>/`.
pub(crate) fn ndk_libcxx_path(ndk_path: &Path, abi: AndroidAbi) -> PathBuf {
    let new_path = ndk_path
        .join("toolchains/llvm/prebuilt")
        .join(ndk_host_tag(ndk_path))
        .join("sysroot/usr/lib")
        .join(abi.ndk_libcxx_triple())
        .join("libc++_shared.so");

    if new_path.exists() {
        return new_path;
    }

    ndk_path
        .join("sources/cxx-stl/llvm-libc++/libs")
        .join(abi.as_str())
        .join("libc++_shared.so")
}

/// The linker flag that aligns every produced ELF's `LOAD` segments to 16 KB
/// pages — the largest page size Android ships (Pixel 9 class) and Google
/// Play's packaging requirement. The app and every preview module it
/// `dlopen`s must carry the same flag.
pub(crate) const ANDROID_MAX_PAGE_SIZE_LINK_ARG: &str = "-Clink-arg=-Wl,-z,max-page-size=16384";

/// Represents an Android platform for a specific architecture.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum AndroidAbi {
    /// ARM64 (arm64-v8a) - modern Android devices
    Arm64V8a,
    /// `x86_64` - emulators on Intel/AMD
    X86_64,
    /// `ARMv7` (armeabi-v7a) - older 32-bit devices
    ArmeabiV7a,
    /// x86 - older 32-bit emulators
    X86,
}

/// Error returned when parsing an unsupported Android ABI string.
#[derive(Debug, thiserror::Error)]
#[error("Unsupported Android ABI: {abi}")]
pub struct UnsupportedAndroidAbi {
    abi: String,
}

impl FromStr for AndroidAbi {
    type Err = UnsupportedAndroidAbi;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "arm64-v8a" => Ok(Self::Arm64V8a),
            "x86_64" => Ok(Self::X86_64),
            "armeabi-v7a" => Ok(Self::ArmeabiV7a),
            "x86" => Ok(Self::X86),
            other => Err(UnsupportedAndroidAbi {
                abi: other.to_string(),
            }),
        }
    }
}

impl AndroidAbi {
    #[must_use]
    /// Android ABI string used by the Android toolchain (e.g. `arm64-v8a`).
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Arm64V8a => "arm64-v8a",
            Self::X86_64 => "x86_64",
            Self::ArmeabiV7a => "armeabi-v7a",
            Self::X86 => "x86",
        }
    }

    #[must_use]
    /// Target triple prefix used by the NDK toolchain binaries (clang, clang++).
    pub const fn ndk_target(self) -> &'static str {
        match self {
            Self::Arm64V8a => "aarch64-linux-android",
            Self::X86_64 => "x86_64-linux-android",
            Self::ArmeabiV7a => "armv7a-linux-androideabi",
            Self::X86 => "i686-linux-android",
        }
    }

    #[must_use]
    /// Target triple used by NDK sysroot libc++ paths.
    pub const fn ndk_libcxx_triple(self) -> &'static str {
        match self {
            Self::Arm64V8a => "aarch64-linux-android",
            Self::X86_64 => "x86_64-linux-android",
            Self::ArmeabiV7a => "arm-linux-androideabi",
            Self::X86 => "i686-linux-android",
        }
    }

    /// The Rust target triple this ABI builds for — the one mapping every
    /// ABI-to-triple question reads; [`AndroidAbi::from_triple`] is its
    /// inverse.
    #[must_use]
    pub const fn triple(self) -> Triple {
        let (architecture, environment) = match self {
            Self::Arm64V8a => (
                Architecture::Aarch64(Aarch64Architecture::Aarch64),
                Environment::Android,
            ),
            Self::X86_64 => (Architecture::X86_64, Environment::Android),
            // rustc's armv7 Android target carries the `androideabi`
            // environment (`armv7-linux-androideabi`); `android` alone names
            // no target.
            Self::ArmeabiV7a => (
                Architecture::Arm(target_lexicon::ArmArchitecture::Armv7),
                Environment::Androideabi,
            ),
            Self::X86 => (
                Architecture::X86_32(target_lexicon::X86_32Architecture::I686),
                Environment::Android,
            ),
        };
        Triple {
            architecture,
            vendor: Vendor::Unknown,
            operating_system: OperatingSystem::Linux,
            environment,
            binary_format: BinaryFormat::Elf,
        }
    }

    /// The ABI a Rust target triple names — the inverse of
    /// [`AndroidAbi::triple`], so call sites holding a triple never keep
    /// a second copy of the architecture mapping.
    #[must_use]
    pub const fn from_triple(triple: &Triple) -> Option<Self> {
        match triple.architecture {
            Architecture::Aarch64(_) => Some(Self::Arm64V8a),
            Architecture::X86_64 => Some(Self::X86_64),
            Architecture::Arm(target_lexicon::ArmArchitecture::Armv7) => Some(Self::ArmeabiV7a),
            Architecture::X86_32(target_lexicon::X86_32Architecture::I686) => Some(Self::X86),
            _ => None,
        }
    }
}

