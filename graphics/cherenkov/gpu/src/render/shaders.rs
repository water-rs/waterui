//! Loading of the engine's fixed shader modules (issue #57).
//!
//! `build.rs` compiles every fixed WGSL module once with naga; the runtime
//! embeds the results and loads them through wgpu's passthrough shader API,
//! so no naga translation, bounds checks or loop bounding run at device or
//! pipeline creation. The passthrough path is safe here because the sources
//! are fixed strings shipped with the crate and validated at build time —
//! unlike the user-supplied shader sources in `paint` and `interop`, which
//! keep the checked WGSL path.
//!
//! Delivery by backend:
//!
//! - **Vulkan** gets naga's SPIR-V emission. The `.spv` artifacts exist
//!   only on the non-Apple, non-wasm targets where wgpu compiles its
//!   Vulkan backend (issue #241), so SPIR-V is embedded there only.
//! - **Metal** gets a `.metallib` compiled by `xcrun` during the build.
//! - **DX12** gets DXIL compiled by `dxc` during the build, embedded on
//!   Windows targets only, where wgpu compiles its DX12 backend (issue
//!   #2726). A DXIL module holds one entry point and a vertex stage is
//!   compiled against the fragment stage it links with, so each
//!   [`RenderProgram`] stage and each [`ComputeProgram`] is its own
//!   module.
//! - **Everything else keeps WGSL** as a backend property, not a fallback:
//!   wgpu 29 has no GLSL producer to feed GL's passthrough input, and
//!   wasm/WebGPU keeps WGSL by design.

use std::borrow::Cow;

use cherenkov::{EngineError, ResourceError};

use super::programs::{self, ComputeLayout, Program};

/// A render pipeline's stage modules and entry points.
#[derive(Debug)]
pub struct RenderProgram {
    /// The vertex stage's module.
    pub vertex: wgpu::ShaderModule,
    /// The vertex entry point.
    pub vertex_entry: &'static str,
    /// The fragment stage's module.
    pub fragment: wgpu::ShaderModule,
    /// The fragment entry point.
    pub fragment_entry: &'static str,
}

/// A compute pipeline's module, entry point and layout.
#[derive(Debug)]
pub struct ComputeProgram {
    /// The module.
    pub module: wgpu::ShaderModule,
    /// The entry point.
    pub entry: &'static str,
    /// The pipeline's bind group layout.
    pub layout: ComputeLayout,
}

/// The engine module's programs, in `CoveragePass::program` order: the
/// painter, then the opaque and partial coverage phases.
pub type EnginePrograms = [RenderProgram; 3];

/// The engine programs of `module`, a checked WGSL module holding every
/// engine entry point — a user backdrop effect's composed module.
#[must_use]
pub fn wgsl_engine_programs(module: &wgpu::ShaderModule) -> EnginePrograms {
    programs::ENGINE.map(|program| match program {
        Program::Render { vertex, fragment } => RenderProgram {
            vertex: module.clone(),
            vertex_entry: vertex,
            fragment: module.clone(),
            fragment_entry: fragment,
        },
        Program::Compute { .. } => unreachable!("programs::ENGINE is render only"),
    })
}

