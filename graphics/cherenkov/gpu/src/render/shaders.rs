/// One embedded DXIL stage and the metadata needed to load its entry point.
#[cfg(cherenkov_dxil)]
pub struct DxilStage {
    /// The signed DXIL container.
    pub dxil: &'static [u8],
    /// The stage's passthrough entry-point metadata.
    pub entry: wgpu::PassthroughShaderEntryPoint<'static>,
}

/// One fixed module's source and precompiled artifacts.
struct Fixed {
    /// WGSL source — the fallback text and the input `build.rs` compiled.
    wgsl: &'static str,
    /// naga's SPIR-V emission as little-endian bytes. The field
    /// exists only where the artifacts do — [`spirv`]'s targets (issue
    /// #241) — so no build carries a dummy empty slice.
    #[cfg(cherenkov_spirv)]
    spirv: &'static [u8],
    /// The `xcrun metallib` output, present only in Apple builds.
    metallib: &'static [u8],
    /// The `dxc` output, indexed like the `dxil` module's tables; only on
    /// Windows targets (issue #2726).
    #[cfg(cherenkov_dxil)]
    dxil: &'static [DxilStage],
    /// The pipelines the module serves.
    programs: &'static [Program],
    /// The module's entry points, generated by build.rs from its validated
    /// Naga module for passthrough creation in wgpu 30.
    entries: &'static [wgpu::PassthroughShaderEntryPoint<'static>],
}

