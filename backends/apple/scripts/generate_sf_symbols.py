#!/usr/bin/env python3
"""Generate typed `SfSymbol` catalog and release availability tables.

Reads Apple's `CoreGlyphs.bundle/Contents/Resources/name_availability.plist`,
maps every SF Symbol name to a collision-free Rust `SCREAMING_SNAKE_CASE`
constant on `waterui_apple::SfSymbol`, gates each constant on its release key,
and writes the committed Rust sources under `backends/apple/src/`.
"""

from __future__ import annotations

import argparse
import pathlib
import plistlib
import re
import shutil
import subprocess
import sys

DEFAULT_PLIST = pathlib.Path(
    "/System/Library/CoreServices/CoreGlyphs.bundle/Contents/Resources/name_availability.plist"
)

RUST_KEYWORDS = frozenset(
    {
        "abstract",
        "as",
        "async",
        "await",
        "become",
        "box",
        "break",
        "const",
        "continue",
        "crate",
        "do",
        "dyn",
        "else",
        "enum",
        "extern",
        "false",
        "final",
        "fn",
        "for",
        "gen",
        "if",
        "impl",
        "in",
        "let",
        "loop",
        "macro",
        "match",
        "mod",
        "move",
        "mut",
        "override",
        "priv",
        "pub",
        "ref",
        "return",
        "self",
        "Self",
        "static",
        "struct",
        "super",
        "trait",
        "true",
        "try",
        "type",
        "typeof",
        "unsafe",
        "unsized",
        "use",
        "virtual",
        "where",
        "while",
        "yield",
    }
)


def parse_version(text: str) -> tuple[int, int, int]:
    parts = [int(part) for part in text.strip().split(".")]
    if not 1 <= len(parts) <= 3:
        raise ValueError(f"unexpected Apple OS version string: {text!r}")
    while len(parts) < 3:
        parts.append(0)
    return (parts[0], parts[1], parts[2])


def symbol_to_ident(name: str) -> str:
    if not name:
        raise ValueError("symbol name must not be empty")
    ident = re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_").upper()
    if not ident:
        raise ValueError(f"symbol name {name!r} produced an empty Rust identifier")
    if ident[0].isdigit():
        ident = f"_{ident}"
    if ident in RUST_KEYWORDS:
        raise ValueError(f"symbol name {name!r} maps to Rust keyword {ident!r}")
    if not re.fullmatch(r"[A-Z_][A-Z0-9_]*", ident):
        raise ValueError(f"symbol name {name!r} produced invalid Rust identifier {ident!r}")
    return ident


def build_sources(data: dict) -> tuple[str, str]:
    symbols = data.get("symbols")
    releases = data.get("year_to_release")
    if not isinstance(symbols, dict) or not isinstance(releases, dict):
        raise ValueError("plist must contain `symbols` and `year_to_release` dictionaries")

    sorted_releases = sorted(
        releases.items(),
        key=lambda item: tuple(int(p) for p in item[0].split(".")),
    )
    release_lines = [
        "// @generated by backends/apple/scripts/generate_sf_symbols.py — do not edit by hand.",
        "",
        "/// One SF Symbols release row: `(release_key, macos, ios, tvos, watchos, visionos)`.",
        "#[expect(",
        "    clippy::type_complexity,",
        '    reason = "generated flat release table matching build.rs without helper structs"',
        ")]",
        "pub const SF_SYMBOL_RELEASES: &[(&str, (u16, u16, u16), (u16, u16, u16), (u16, u16, u16), (u16, u16, u16), (u16, u16, u16))] = &[",
    ]
    for year, versions in sorted_releases:
        macos = parse_version(versions["macOS"])
        ios = parse_version(versions["iOS"])
        tvos = parse_version(versions["tvOS"])
        watchos = parse_version(versions["watchOS"])
        visionos = parse_version(versions["visionOS"])
        release_lines.append(
            f'    ("{year}", {macos!r}, {ios!r}, {tvos!r}, {watchos!r}, {visionos!r}),'
        )
    release_lines.append("];")
    release_lines.append("")

    seen_idents: dict[str, str] = {}
    by_release: dict[str, list[tuple[str, str]]] = {key: [] for key in releases}
    for raw_name, release_key in sorted(symbols.items()):
        if release_key not in releases:
            raise ValueError(
                f"symbol {raw_name!r} references unknown release {release_key!r}"
            )
        ident = symbol_to_ident(raw_name)
        previous = seen_idents.get(ident)
        if previous is not None:
            raise ValueError(
                f"identifier collision for {ident!r}: {previous!r} and {raw_name!r}"
            )
        seen_idents[ident] = raw_name
        by_release[release_key].append((ident, raw_name))

    catalog_lines = [
        "// @generated by backends/apple/scripts/generate_sf_symbols.py — do not edit by hand.",
        "",
        "macro_rules! sf_symbols {",
        "    ($( $release:literal => { $( ($ident:ident, $name:literal) ),* $(,)? } ),* $(,)?) => {",
        "        impl super::SfSymbol {",
        "            $(",
        "                $(",
        '                    #[doc = concat!("SF Symbol `\\"", $name, "\\"`.")]',
        "                    #[cfg(sf_symbol_release = $release)]",
        "                    pub const $ident: Self = Self::from_static($name);",
        "                )*",
        "            )*",
        "        }",
        "    };",
        "}",
        "",
        "sf_symbols! {",
    ]
    for release_key, release_entries in by_release.items():
        if not release_entries:
            continue
        catalog_lines.append(f'    "{release_key}" => {{')
        for ident, raw_name in release_entries:
            catalog_lines.append(f'        ({ident}, "{raw_name}"),')
        catalog_lines.append("    },")
    catalog_lines.append("}")
    catalog_lines.append("")

    return rustfmt("\n".join(release_lines)), rustfmt("\n".join(catalog_lines))


def rustfmt(source: str) -> str:
    exe = shutil.which("rustfmt")
    if exe is None:
        return source
    proc = subprocess.run(
        [exe, "--edition", "2024"],
        input=source,
        text=True,
        capture_output=True,
        check=True,
    )
    return proc.stdout


def run_self_tests() -> None:
    assert symbol_to_ident("house") == "HOUSE"
    assert symbol_to_ident("house.fill") == "HOUSE_FILL"
    assert symbol_to_ident("0.circle") == "_0_CIRCLE"

    try:
        build_sources(
            {
                "year_to_release": {
                    "2019": {
                        "macOS": "10.15",
                        "iOS": "13.0",
                        "tvOS": "13.0",
                        "watchOS": "6.0",
                        "visionOS": "1.0",
                    }
                },
                "symbols": {"a.b": "2019", "a-b": "2019"},
            }
        )
    except ValueError as err:
        assert "collision" in str(err), err
    else:
        raise AssertionError("expected collision to fail")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--plist", type=pathlib.Path, default=DEFAULT_PLIST)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()

    run_self_tests()
    if args.self_test:
        return 0

    with args.plist.open("rb") as fh:
        data = plistlib.load(fh)
    releases_src, catalog_src = build_sources(data)

    src_dir = pathlib.Path(__file__).resolve().parent.parent / "src"
    releases_path = src_dir / "sf_symbol_releases.rs"
    catalog_path = src_dir / "sf_symbol_catalog.rs"

    if args.check:
        if releases_path.read_text() != releases_src or catalog_path.read_text() != catalog_src:
            print("generated SF Symbol sources are out of date", file=sys.stderr)
            return 1
        return 0

    releases_path.write_text(releases_src)
    catalog_path.write_text(catalog_src)
    print(f"wrote {releases_path} and {catalog_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
