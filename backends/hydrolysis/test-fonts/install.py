def write_verified(name: str, data: bytes) -> None:
    digest = sha256(data)
    if digest != EXPECTED[name]:
        raise SystemExit(
            f"{name}: generated sha256 {digest} != expected {EXPECTED[name]}\n"
            "the font bytes are part of the test contract — investigate the "
            "source or fonttools version drift instead of accepting the output"
        )
    (OUT_DIR / name).write_bytes(data)
    print(f"  wrote {name} ({len(data)} bytes, {digest[:12]}…)")


def user_font_dir() -> Path:
    """The directory fonts are installed into for the current user."""
    if sys.platform == "darwin":
        return Path.home() / "Library" / "Fonts"
    if sys.platform == "linux":
        return Path.home() / ".local" / "share" / "fonts"
    if sys.platform == "win32":
        local_app_data = os.environ.get("LOCALAPPDATA")
        if local_app_data is None:
            raise SystemExit(
                "LOCALAPPDATA is not set — cannot locate the per-user Fonts directory"
            )
        return Path(local_app_data) / "Microsoft" / "Windows" / "Fonts"
    raise SystemExit(
        f"unsupported platform {sys.platform!r}: the test fonts install on "
        "macOS, Linux and Windows only"
    )


def register_windows_font(path: Path) -> None:
    """Register `path` under the per-user Fonts key so DirectWrite sees it."""
    import winreg

    face = TTFont(str(path), lazy=True)
    full_name = face["name"].getDebugName(4) or path.stem
    kind = "OpenType" if face.sfntVersion == "OTTO" else "TrueType"
    face.close()
    key_path = r"Software\Microsoft\Windows NT\CurrentVersion\Fonts"
    with winreg.CreateKeyEx(
        winreg.HKEY_CURRENT_USER, key_path, 0, winreg.KEY_SET_VALUE
    ) as key:
        winreg.SetValueEx(key, f"{full_name} ({kind})", 0, winreg.REG_SZ, str(path))


def broadcast_windows_font_change() -> None:
    """Post WM_FONTCHANGE so already-running applications pick the fonts up."""
    import ctypes
    from ctypes import wintypes

    send_message_timeout = ctypes.windll.user32.SendMessageTimeoutW
    send_message_timeout.argtypes = [
        wintypes.HWND,
        wintypes.UINT,
        wintypes.WPARAM,
        wintypes.LPARAM,
        wintypes.UINT,
        wintypes.UINT,
        ctypes.POINTER(wintypes.DWORD),
    ]
    send_message_timeout.restype = wintypes.LPARAM
    HWND_BROADCAST = 0xFFFF
    WM_FONTCHANGE = 0x001D
    SMTO_ABORTIFHUNG = 0x0002
    result = wintypes.DWORD(0)
    send_message_timeout(
        HWND_BROADCAST,
        WM_FONTCHANGE,
        0,
        0,
        SMTO_ABORTIFHUNG,
        1000,
        ctypes.byref(result),
    )


def install() -> None:
    """Install every font in `EXPECTED` into the current user's font location.

    Idempotent: a file already installed byte-identically is left alone.
    """
    target = user_font_dir()
    target.mkdir(parents=True, exist_ok=True)
    print(f"installing into {target}")
    for name in sorted(EXPECTED):
        data = (OUT_DIR / name).read_bytes()
        dest = target / name
        if dest.is_file() and sha256(dest.read_bytes()) == sha256(data):
            print(f"  {name}: already installed")
        else:
            dest.write_bytes(data)
            print(f"  {name}: installed")
        if sys.platform == "win32":
            register_windows_font(dest)
    if sys.platform == "linux":
        try:
            subprocess.run(["fc-cache", "-f", str(target)], check=True)
        except FileNotFoundError:
            raise SystemExit(
                "fc-cache not found — fontconfig is required for the installed "
                "fonts to be discovered"
            )
        except subprocess.CalledProcessError as error:
            raise SystemExit(f"fc-cache -f {target} failed: {error}")
    elif sys.platform == "win32":
        broadcast_windows_font_change()


def main() -> None:
    with tempfile.TemporaryDirectory(prefix="hydrolysis-test-fonts-") as tmp:
        work = Path(tmp)

        # Roboto — the faces the `water` CLI ships to applications.
        roboto_zip = fetch(
            "https://github.com/googlefonts/roboto/releases/download/v2.138/roboto-android.zip",
            "c825453253f590cfe62557733e7173f9a421fff103b00f57d33c4ad28ae53baf",
        )
