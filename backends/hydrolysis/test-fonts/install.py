OUT_DIR = Path(__file__).resolve().parent


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def fetch(url: str, expected_sha256: str) -> bytes:
    """Download `url` and verify its SHA-256."""
    print(f"fetch {url}")
    data = None
    for attempt in range(4):
        try:
            data = urllib.request.urlopen(url, timeout=120).read()
            break
        except Exception as error:  # noqa: BLE001 — report and retry, pin wins
            if attempt == 3:
                raise SystemExit(f"fetch {url} failed after 4 attempts: {error}")
            import time

            time.sleep(2**attempt * 2)
    digest = sha256(data)
    if digest != expected_sha256:
        raise SystemExit(
            f"sha256 mismatch for {url}:\n  got      {digest}\n  expected {expected_sha256}"
        )
    return data


def zip_member(archive: bytes, name: str) -> bytes:
    with zipfile.ZipFile(io.BytesIO(archive)) as zf:
        return zf.read(name)


def deb_member(deb: bytes, name: str) -> bytes:
    """Extract `name` from the data tarball of a Debian binary package.

    Reads the `ar` container directly (no `dpkg`/`ar` dependency, so this runs
    identically on Linux, macOS and Windows runners).
    """
    assert deb[:8] == b"!<arch>\n", "not an ar archive"
    offset = 8
    data_tar = None
    while offset < len(deb):
        header = deb[offset : offset + 60]
        member_name = header[:16].decode().strip()
        size = int(header[48:58].decode().strip())
        body = deb[offset + 60 : offset + 60 + size]
        offset += 60 + size + (size % 2)
        if member_name.startswith("data.tar"):
            data_tar = (member_name, body)
            break
    if data_tar is None:
        raise SystemExit("deb carries no data.tar member")
    _, body = data_tar
    with tarfile.open(fileobj=io.BytesIO(body)) as tf:
        member = tf.extractfile(name)
        assert member is not None, f"{name} not in data.tar"
        return member.read()


def pyftsubset(source: Path, out: Path, unicodes: str, extra_args: list[str]) -> None:
    """Run pyftsubset's entry point with its CLI flags, in-process."""
    args = [
        str(source),
        f"--unicodes={unicodes}",
        f"--output-file={out}",
        *extra_args,
    ]
    rc = subset.main(args)
    if rc not in (0, None):
        raise SystemExit(f"pyftsubset failed for {source} ({rc})")


