"""Build Hydrolysis's test fonts from pinned sources and install them.

Hydrolysis's rendering tests and the styled `waterui-testing` suites resolve
these faces by family name through system font discovery — no font bytes are
compiled into any crate. A machine that has not run this script fails those
tests with an error naming the missing family. Install once per machine:

    uv run backends/hydrolysis/test-fonts/install.py

Every downloaded artifact is pinned by URL and verified by SHA-256, and every
font the script produces is verified against its expected SHA-256 — the
generated bytes are part of the test contract, so a drifted output is a hard
failure, never a silent regeneration. The fonts themselves are binary assets
and stay out of the repository (see the repository's no-binary-assets rule);
`test-fonts/*.ttf` and `*.otf` are gitignored.

The verified fonts are then installed into the current user's font location:

- macOS: `~/Library/Fonts`
- Linux: `~/.local/share/fonts`, followed by `fc-cache -f` on that directory
- Windows: `%LOCALAPPDATA%\\Microsoft\\Windows\\Fonts`, registered per-user
  under `HKCU\\Software\\Microsoft\\Windows NT\\CurrentVersion\\Fonts`

On Windows the script returns only after DirectWrite's system font collection
resolves every installed family. The files and the per-user registry values
can be visible before that collection is, and a test that starts in between
fails its family lookup. Family names come from each font's name table: the
weight-stretch-style family (name ID 21, otherwise 16, otherwise 1), which is
the name `GetSystemFontCollection` groups by. The script polls
`IDWriteFactory::GetSystemFontCollection` with `checkForUpdates` true
and `IDWriteFontCollection::FindFamilyName` about every 250 ms, for up to
120 seconds, and prints how long it waited. If the deadline passes it exits
non-zero, naming each family still unresolved.

Re-running is idempotent: a font already installed byte-identically is left
in place; anything else is replaced. Any other platform is a hard error.
"""

